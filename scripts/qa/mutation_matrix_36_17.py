"""phase-36.17 criterion 7 -- re-runnable mutation matrix.

WHY THIS FILE EXISTS
--------------------
Criterion 7 requires every new guard to be mutation-tested, in BOTH directions
for the ordering change. The cycle-1..5 matrices were produced by a scratch
script that was never committed, so the transcript in the step artifacts could
not be regenerated by anyone -- including me. This harness makes criterion 7
re-runnable.

SAFETY -- THIS HARNESS NEVER WRITES TO THE REPOSITORY
-----------------------------------------------------
An earlier scratch harness mutated the LIVE
`backend/services/autonomous_loop.py` while an ARMED backend was running. No
harm occurred (CPython serves an imported module from `sys.modules` and never
re-reads the file), but a restart inside any of those windows would have
imported a mutant into an armed trading process, and a tool timeout did once
leave a mutant on disk.

So each mutant here is applied **in memory**, inside a throwaway subprocess
that registers the mutated module object in `sys.modules` BEFORE pytest
imports anything. The on-disk file is opened read-only and never rewritten.
`--verify-clean` (default on) digests the target before and after the whole
run and fails if they differ.

DISCIPLINE ENCODED HERE
-----------------------
* Every mutation anchor must occur **exactly once** in the source. A
  no-match `str.replace` is indistinguishable from success, so an anchor that
  matches 0 or 2+ times is a hard error, not a skipped cell.
* The mutated source must differ from the original -- asserted, not assumed.
* The un-mutated **baseline must be GREEN first**. A "killed" mutant proves
  nothing if the tree was already red.
* A **restored** run is executed last, so the transcript shows the tree green
  on both sides of the matrix.
* Each cell runs the WHOLE module (no `-k` filter), so the transcript names
  which tests catch the mutant and carries no `deselected` count -- that count
  moves every time the step adds a test and has gone stale three times.

USAGE
-----
    source .venv/bin/activate
    python scripts/qa/mutation_matrix_36_17.py

Do NOT run this concurrently with any other pytest invocation: the module's
autouse `_live_audit_file_is_write_protected` fixture byte-compares the live
`handoff/kill_switch_audit.jsonl`, so a second run turns this one RED.
"""
