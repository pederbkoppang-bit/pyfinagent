    print(f"md5      : {digest_before}  (read-only; mutants are in-memory)")

    rc, out = _run(None, None)
    baseline = _summary_line(out)
    print(f"[baseline] un-mutated tree: {baseline}")
    if rc != 0:
        print("BASELINE IS RED -- aborting. A 'killed' mutant proves nothing here.")
        print(out[-4000:])
        return 2

    cells = [m for m in MUTANTS if not args.only or m["id"] == args.only]
    killed, survived, broken = 0, [], []

    for m in cells:
        rc, out = _run(m["old"], m["new"])
        summary = _summary_line(out)
        if rc in (96, 97):
            broken.append(m["id"])
            verdict = "BROKEN"
        elif rc == 0:
            survived.append(m["id"])
            verdict = "SURVIVED"
        else:
            killed += 1
            verdict = "KILLED  "
        print(f"  {verdict}| {m['id']}: {m['desc']}")
        print(f"           proves: {m['proves']}")
        tests = _failed_tests(out)
        if tests:
            print(f"           tests : {', '.join(tests)}")
        print(f"           result: {summary}")

    rc, out = _run(None, None)
    print(f"[restored] un-mutated tree: {_summary_line(out)}")

    digest_after = _md5(TARGET)
    same = digest_before == digest_after
    print(f"[integrity] target md5 unchanged: {same} ({digest_after})")

    total = len(cells)
    if broken:
        print(f"MATRIX BROKEN -- anchors failed for: {', '.join(broken)}")
        return 3
    if survived:
        print(f"{killed} of {total} killed. SURVIVORS: {', '.join(survived)}")
        return 1
    if not same:
        print("TARGET FILE CHANGED DURING THE RUN -- investigate before trusting this.")
        return 4
    # SCOPED deliberately. "Every new guard can fail" is a GLOBAL claim this
    # matrix does not license -- the cycle-5 Q/A said so and was right. This
    # matrix mutates autonomous_loop.py only, so it can speak for the guards
    # over the halt-branch pass and nothing else. The test-isolation guards in
    # the same module are proven falsifiable separately, by demonstration.
    print(f"ALL {total} MUTANTS KILLED -- every guard IN THIS MATRIX can fail.")
    return 0


