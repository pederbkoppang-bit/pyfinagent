# The bootstrap that runs inside each subprocess. It injects the (possibly
# mutated) module into sys.modules BEFORE pytest imports anything, so nothing
# is ever written to disk.
BOOTSTRAP = r"""
import importlib.util, json, os, sys

spec = json.load(open(os.environ["MUT3617_SPEC"], encoding="utf-8"))
target, modname = spec["target"], spec["modname"]
src = open(target, encoding="utf-8").read()
original = src

old, new = spec.get("old"), spec.get("new")
if old is not None:
    n = src.count(old)
    if n != 1:
        sys.stderr.write("ANCHOR NOT UNIQUE: %d occurrence(s)\n" % n)
        raise SystemExit(97)
    src = src.replace(old, new, 1)
    if src == original:
        sys.stderr.write("MUTATION WAS A NO-OP\n")
        raise SystemExit(96)

import backend.services  # parent package; empty __init__

mod = importlib.util.module_from_spec(
    importlib.util.spec_from_file_location(modname, target)
)
sys.modules[modname] = mod
exec(compile(src, target, "exec"), mod.__dict__)
setattr(sys.modules["backend.services"], "autonomous_loop", mod)

import pytest
raise SystemExit(pytest.main(spec["pytest_args"]))
"""


def _md5(path: Path) -> str:
    return hashlib.md5(path.read_bytes()).hexdigest()


def _run(old: str | None, new: str | None) -> tuple[int, str]:
    """Run the test module against an in-memory (possibly mutated) source."""
    payload = {
        "target": str(TARGET),
        "modname": MODNAME,
        "old": old,
        "new": new,
        "pytest_args": [TEST_MODULE, "-q", "-p", "no:randomly", "--no-header"],
    }
    fd, spec_path = tempfile.mkstemp(prefix="mut3617_", suffix=".json")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            json.dump(payload, fh)
        env = dict(os.environ, MUT3617_SPEC=spec_path, PYTHONDONTWRITEBYTECODE="1")
        proc = subprocess.run(
            [sys.executable, "-c", BOOTSTRAP],
            cwd=str(REPO_ROOT),
            env=env,
            capture_output=True,
            text=True,
        )
    finally:
        os.unlink(spec_path)
    return proc.returncode, (proc.stdout + proc.stderr)


def _summary_line(out: str) -> str:
    """The pytest one-line summary (last non-empty line that names a count)."""
    for line in reversed(out.strip().splitlines()):
        s = line.strip()
        if ("passed" in s or "failed" in s or "error" in s) and " in " in s:
            return s.strip("= ").strip()
    return "NO SUMMARY (see stderr)"


def _failed_tests(out: str) -> list[str]:
    names = []
    for line in out.splitlines():
        if line.startswith("FAILED "):
            frag = line.split(" ", 1)[1].split(" ")[0]
            names.append(frag.rsplit("::", 1)[-1])
    return names


